-- User Profile
CREATE TABLE user_profiles (
    user_id BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    nationality VARCHAR(100),
    major VARCHAR(100),
    bio TEXT,
    color SMALLINT NOT NULL DEFAULT 1
        CHECK (color BETWEEN 1 AND 4),

    CONSTRAINT fk_user_profiles_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- Languages
CREATE TABLE languages (
    language_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_name VARCHAR(100) NOT NULL UNIQUE
);

-- User Languages
CREATE TABLE user_languages (
    user_id BIGINT NOT NULL,
    language_id BIGINT NOT NULL,

    PRIMARY KEY (user_id, language_id),

    CONSTRAINT fk_user_languages_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_languages_language
        FOREIGN KEY (language_id)
        REFERENCES languages(language_id)
);

-- Interests
CREATE TABLE interests (
    interest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interest_name VARCHAR(100) NOT NULL UNIQUE
);

-- User Interests
CREATE TABLE user_interests (
    user_id BIGINT NOT NULL,
    interest_id BIGINT NOT NULL,

    PRIMARY KEY (user_id, interest_id),

    CONSTRAINT fk_user_interests_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_interests_interest
        FOREIGN KEY (interest_id)
        REFERENCES interests(interest_id)
);

