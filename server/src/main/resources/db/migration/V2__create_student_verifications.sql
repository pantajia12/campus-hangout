CREATE TABLE student_verifications (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    rejection_reason VARCHAR(255),
    submitted_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP,

    CONSTRAINT fk_student_verifications_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT chk_student_verification_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_student_verifications_user_id
    ON student_verifications(user_id);
